#!/usr/bin/env python3
"""Generate matching Swift/Rust tables from the pinned WHATWG entity source."""
import json
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = json.loads((root / 'shared/header-entities.json').read_text())
rows = sorted(source['entries'].items())
assert len(rows) == 2125
assert all(re.fullmatch('[A-Za-z][A-Za-z0-9]*',k) and isinstance(v,str) for k,v in rows)

def quoted(value):
    return '"'+''.join(c if 32<=ord(c)<127 and c not in '\\"' else '\\u{'+format(ord(c),'x')+'}' for c in value)+'"'

swift = root / 'macos/MessageText/HTMLNames.swift'
current = swift.read_text()
start = current.index('    private static let entries:')
body = '    private static let entries: [(String, String)] = [\n'+''.join('        ('+quoted(k)+', '+quoted(v)+'),\n' for k,v in rows)+'    ]\n}\n'
swift_text = re.sub(r'Source SHA256: [a-f0-9]+', 'Source SHA256: '+source['sha256'],current[:start])+body
rust_text = '// Generated by scripts/generate-entities.py. Do not edit.\n// '+source['source']+'\n// Source SHA256: '+source['sha256']+'\n'
rust_text += 'pub(super) const ENTRIES: &[(&str, &str)] = &[\n'+''.join('    ('+quoted(k)+', '+quoted(v)+'),\n' for k,v in rows)+'];\n'
for path, text in [(swift, swift_text), (root/'crates/mail-core/src/header_text/names.rs', rust_text)]:
    if '--check' in sys.argv:
        assert path.read_text() == text, f'{path} needs regeneration'
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
